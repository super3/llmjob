"""split.py (no arguments): writes probes/hand89/fold_h.cuh and fold_h_common.inc from src/pearl_fold_draw.cuh (commit a1f7228a's
line numbers). The fold is the same; the chunk loop and everything that uses the 160 sums moves into a function of
its own that is not inlined, so its code can be replaced whole by a loop written by hand (hand89/fold.py)."""
import os
import sys

dst = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(dst, "..", "..", "src", "pearl_fold_draw.cuh")
L = open(src, encoding="utf-8").read().split("\n")


def rng(a, b):
    """Lines a..b of the source, 1-based, inclusive."""
    return L[a - 1:b]


assert L[211 - 1].startswith("#if defined(__CUDA_ARCH__)"), L[210]
assert "constexpr uint32_t MT = PD_MT" in L[212 - 1]
assert "if (blockDim.x != PD_THREADS) return;" in L[215 - 1]
assert "for (uint32_t v = blockIdx.x" in L[345 - 1]
assert L[392 - 1].strip() == "__syncthreads();" and L[394 - 1].strip() == "#pragma unroll"
assert "uint32_t bad = 0u;" in L[426 - 1]
assert L[656 - 1].strip() == "#undef PD_LOOP"
assert "fold_end(fold_tile(t)" in L[668 - 1]
assert "bar.sync" in L[671 - 1]
assert "if (PD_T_STAMP)" in L[702 - 1] and "else if ((int)bad < 0)" in L[703 - 1]
assert L[709 - 1].strip() == "}" and L[708 - 1].strip() == "__syncthreads();"

common = rng(212, 214) + rng(216, 218) + rng(223, 343)
head = rng(1, 199)
out = []
out += ["// GENERATED by probes/hand89/split.py from src/pearl_fold_draw.cuh (commit a1f7228a). The same fold, with the",
        "// chunk loop in a function of its own (PD_LOOPFN, never inlined): hand89/fold.py replaces that function's code",
        "// in the cubin with a loop written by hand. As compiled here it is the reference the hand loop is checked",
        "// against. The comments below are the original file's.", "//"]
out += head
out += ["",
        "#define PD_CAT2(a, b) a##b",
        "#define PD_CAT(a, b) PD_CAT2(a, b)",
        "#define PD_LOOPFN PD_CAT(PD_FN, _loop)",
        "",
        "// The tile's fold: zero sums, the first fragments, the chunk loop, the last readouts. It takes nothing from",
        "// the kernel but these two values; every lane constant is made again here.",
        "static __device__ __noinline__ void PD_LOOPFN(const uint4 *__restrict__ offs, uint32_t chunks) {",
        "#if defined(__CUDA_ARCH__) && __CUDA_ARCH__ >= 800",
        '#include "fold_h_common.inc"']
out += rng(370, 376)          # aD/aF of the tile, pOffL
out += rng(394, 415)          # zero sums, first fragments, first offsets
out += rng(423, 656)          # the slot and the loops
out += rng(663, 668)          # the last readouts
out += ["#undef PD_TILE", "#undef PD_TILE4", "#undef PD_KSTEP", "#undef PD_CHUNK", "#endif", "}", ""]
out += rng(201, 211)
out += ['#include "fold_h_common.inc"']
out += rng(215, 215) + rng(220, 221)
out += rng(345, 392)
out += rng(416, 421)
out += ["    PD_LOOPFN(offs, chunks);"]
out += rng(657, 662)
out += rng(670, 701)
out += rng(704, 716)
open(os.path.join(dst, "fold_h.cuh"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
open(os.path.join(dst, "fold_h_common.inc"), "w", encoding="utf-8", newline="\n").write(
    "// GENERATED by probes/hand89/split.py: the declarations the kernel and its loop function both begin with\n"
    "// (lines of src/pearl_fold_draw.cuh, commit a1f7228a).\n" + "\n".join(common) + "\n")
print("fold_h.cuh", len(out), "lines; common", len(common), "lines")
